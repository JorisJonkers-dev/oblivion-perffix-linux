#!/usr/bin/env python3
"""Index every benchmark run into docs/tracking/ so results are kept and comparable.

linux/results/ (one folder per run, git-ignored) holds the raw data: MangoHud CSVs, result.json, report.md. This script
copies each run's report.md into docs/tracking/runs/<folder>.md (small, committed) and regenerates
docs/tracking/runs.md: one row per scene per run, plus one row per A/B report. Folders already indexed are
kept even if the raw folder is deleted later. Safe to run any time; output is deterministic.

Usage: track.py [--results DIR] [--out DIR]
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def fmt(v, nd=1):
    return "" if v is None else (f"{v:.{nd}f}" if isinstance(v, float) else str(v))


def variant(r):
    """Short text for what made this run different: fix mode, ini overrides, extra env, DLL."""
    parts = [f"fix={r.get('fix')}"]
    if r.get("fixIniOverrides"):
        parts.append("ini:" + ",".join(f"{k}={v}" for k, v in r["fixIniOverrides"].items()))
    env = r.get("env") or {}
    extra = {k: v for k, v in env.items()
             if k not in ("WINEDLLOVERRIDES", "MANGOHUD", "MANGOHUD_CONFIGFILE", "OBLV_GAME_ARGS", "OBLV_BENCH_MARKER")}
    if extra:
        parts.append("env:" + ",".join(f"{k}={v}" for k, v in extra.items()))
    if r.get("dll"):
        parts.append(f"dll:{str(r['dll'].get('sha256', ''))[:12]}")
    return " ".join(parts)


def run_rows(folder, r):
    prof = (r.get("profile") or {}).get("name", "")
    rows = []
    for s in r.get("scenes", []):
        rows.append([folder, r.get("label", ""), r.get("scenario", ""), s.get("id", ""), prof, variant(r),
                     fmt(s.get("fps")), fmt(s.get("low1")), fmt(s.get("low01")), fmt(s.get("worstMs")),
                     fmt(s.get("hitches")), fmt(s.get("cpuLoad"), 0), fmt(s.get("gpuLoad"), 0), r.get("outcome", "")])
    if not rows:
        rows.append([folder, r.get("label", ""), r.get("scenario", ""), "-", prof, variant(r),
                     "", "", "", "", "", "", "", r.get("outcome", "")])
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--results", default=str(REPO / "linux" / "results"))
    ap.add_argument("--out", default=str(REPO / "docs" / "tracking"))
    a = ap.parse_args()
    results, out = Path(a.results), Path(a.out)
    copies = out / "runs"
    copies.mkdir(parents=True, exist_ok=True)

    for d in sorted(p for p in results.iterdir() if p.is_dir()) if results.exists() else []:
        rep = d / "report.md"
        if rep.exists():
            shutil.copy2(rep, copies / f"{d.name}.md")
        res = d / "result.json"
        if res.exists():                                     # keep a small result summary next to the report
            r = json.loads(res.read_text())
            keep = {k: r.get(k) for k in ("label", "time", "scenario", "start", "fix", "profile", "fixIniOverrides",
                                          "env", "dll", "outcome", "warnings", "scenes", "loadSec", "diagFiles")}
            for s in keep.get("scenes") or []:
                for k in ("pos", "t0", "t1"):
                    s.pop(k, None)
            (copies / f"{d.name}.json").write_text(json.dumps(keep, indent=1, sort_keys=True) + "\n")

    run_lines, ab_lines = [], []
    for j in sorted(copies.glob("*.json")):
        r = json.loads(j.read_text())
        for row in run_rows(j.stem, r):
            row[0] = f"[{row[0]}](runs/{row[0]}.md)"
            run_lines.append("| " + " | ".join(str(c) for c in row) + " |")
    for m in sorted(copies.glob("*.md")):
        if not (copies / f"{m.stem}.json").exists():         # an A/B report (no result.json of its own)
            title = m.read_text().splitlines()[0].lstrip("# ").strip() if m.stat().st_size else m.stem
            ab_lines.append(f"| [{m.stem}](runs/{m.stem}.md) | {title} |")

    text = ["# Benchmark runs", "",
            "Generated by `linux/track.py` from `linux/results/` (raw data stays there, git-ignored). Do not edit by hand:",
            "add conclusions to [LOG.md](LOG.md). Stats are per scene: avg fps, 1% / 0.1% lows (fps), worst frame (ms),",
            "hitches (frames longer than max(2 x median, 40 ms)), CPU/GPU load (%).", "",
            "## Comparisons (A/B reports)", "", "| report | what |", "|---|---|", *ab_lines, "",
            "## Runs", "",
            "| run | label | scenario | scene | profile | variant | fps | 1% | 0.1% | worst ms | hitches | CPU | GPU | outcome |",
            "|---|---|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---|", *run_lines, ""]
    (out / "runs.md").write_text("\n".join(text))
    print(f"indexed {len(run_lines)} scene rows, {len(ab_lines)} comparisons -> {out / 'runs.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
